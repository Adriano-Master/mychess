#[test]
fn the_window_takes_the_keys_of_the_game_behind() {
    // Control: with the window closed the same key reaches the game.
    let mut control = Rig::sample();
    drop(control.key(Key::Char('e'), Modifiers::NONE));
    assert!(
        !control.shell.app.session.move_entry().text().is_empty(),
        "the key goes to the move entry when no layer is open"
    );
    let mut rig = Rig::sample();
    rig.open_window();
    assert!(rig.shell.modal_layer_open());
    let cursor = rig.shell.app.session.cursor();
    for c in ['e', '4', 'n', 'f'] {
        let task = rig.key(Key::Char(c), Modifiers::NONE);
        assert_eq!(rig.widget_operations(task), 0, "{c}");
    }
    assert!(rig.shell.app.session.move_entry().text().is_empty());
    assert_eq!(rig.shell.app.session.cursor(), cursor);
    // The arrows do not move the game either.
    for key in [NamedKey::Left, NamedKey::Right, NamedKey::Home] {
        drop(rig.key(Key::Named(key), Modifiers::NONE));
    }
    assert_eq!(rig.shell.app.session.cursor(), cursor);
    // Ctrl/Cmd+F goes to the search field of the window (a task), and the
    // game list does not get it.
    let command = Modifiers {
        command: true,
        shift: false,
        alt: false,
    };
    let task = rig.key(Key::Char('f'), command);
    assert!(
        rig.widget_operations(task) >= 1,
        "the field takes the focus"
    );
    assert!(!rig.shell.ui.games.search_focused);
    // F5 makes the report again.
    let task = rig.key(Key::Named(NamedKey::F(5)), Modifiers::NONE);
    assert!(rig.shell.app.opening_report().is_running());
    drop(task);
}

