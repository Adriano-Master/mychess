#[test]
fn clicks_on_orders_themes_and_endgames_set_their_own_filters() {
    let mut rig = Rig::sample();
    rig.open_window();
    // The move order `1.e4 e5 2.Nf3` has four games.
    let order = rig
        .model()
        .blocks
        .iter()
        .find_map(|b| match b {
            Block::Grid(g) => g.rows.iter().flatten().find_map(|c| match c.target {
                Some(mychess_gui::windows::opening_report::Target::Select(
                    ReportSelector::MoveOrder(id),
                )) if c.text == "1.e4 e5 2.Nf3" => Some(id),
                _ => None,
            }),
            _ => None,
        })
        .expect("the main move order");
    let name = target_id(mychess_gui::windows::opening_report::Target::Select(
        ReportSelector::MoveOrder(order),
    ));
    let messages = click_id(rig.tall(), &name);
    for message in messages {
        rig.msg(message);
    }
    assert_eq!(rig.filtered(), 4);
    assert_ply(&rig, 4);
    // The endgame class of every game is `Q,R,BN` (index 7): all five.
    let messages = click_id(rig.tall(), "oprep-link-end-7");
    for message in messages {
        rig.msg(message);
    }
    assert_eq!(rig.filtered(), 5);
    assert_ply(&rig, 4);
    // A theme that no game of the fixture shows selects nothing.
    let messages = click_id(rig.tall(), "oprep-link-theme-2");
    for message in messages {
        rig.msg(message);
    }
    assert_eq!(rig.filtered(), 0);
    assert_ply(&rig, 4);
}

