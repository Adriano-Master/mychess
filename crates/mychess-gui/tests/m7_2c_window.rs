#[test]
fn the_theory_table_has_the_cells_of_the_spec_fixture() {
    let mut rig = Rig::sample();
    rig.open_window();
    let t = rig.theory();
    assert_eq!(t.stem, "1.e4 e5 2.Nf3");
    assert_eq!(t.heading, "+3 =1 -1 (3.5/5: 70%)");
    // The engine merges the rows whose moves are a prefix of the next.
    assert_eq!(t.rows.len(), 3);
    assert!(t.black_first);
    assert_eq!(t.first_number, 2);
    // Black is to move: the first cell repeats the last move of the line.
    assert_eq!(t.rows[0].cells[0].0, "Nf3");
    assert!(
        t.rows
            .iter()
            .all(|r| r.cells[0].0 == "Nf3" || r.cells[0].0 == "...")
    );
    assert_eq!(t.rows[0].cells[1].0, "Nc6");
    assert_eq!(t.rows[2].cells[1].0, "d6");
    // The line copied does not repeat the move twice.
    let line = &t.rows[0].line;
    assert!(line.starts_with("1.e4 e5 2.Nf3 Nc6"), "{line}");
    assert!(!line.contains("Nf3 Nf3"), "{line}");
    assert_eq!(t.rows.iter().map(|r| r.count).sum::<u32>(), 5);
}

