#[test]
fn the_notes_of_the_merged_rows_can_be_followed_and_select_their_games() {
    let mut rig = Rig::wide();
    rig.open_window();
    let t = rig.theory();
    assert!(t.rows.len() <= 9 && t.rows.len() >= 5, "{}", t.rows.len());
    let notes: Vec<(u32, usize)> = rig
        .model()
        .blocks
        .iter()
        .find_map(|b| match b {
            Block::Notes(n) => Some(n.iter().map(|n| (n.number, n.lines.len())).collect()),
            _ => None,
        })
        .expect("the merged rows leave notes");
    assert!(!notes.is_empty());
    let (number, lines) = notes[0];
    assert!(lines >= 1);
    // The marker of the note is on a cell of the table.
    assert!(t.rows.iter().any(|r| r.cells.iter().any(|c| c.1 == number)));
    let name = format!("oprep-link-note-{number}");
    let messages = click_id(rig.tall(), &name);
    for message in messages {
        rig.msg(message);
    }
    assert_eq!(rig.shell.ui.dialogs.oprep.note_focus, Some(number));
    assert!(
        rig.sim(1400.0, 900.0)
            .find(id(&format!("oprep-note-{number}")))
            .is_ok()
    );
    // Clicking the title of the note selects its games.
    let messages = click_id(rig.tall(), &format!("oprep-link-select-note-{number}"));
    for message in messages {
        rig.msg(message);
    }
    assert_eq!(rig.notice(), Some(OpeningReportNotice::FilterSet));
    assert!(
        rig.filtered() >= 1 && rig.filtered() < 60,
        "{}",
        rig.filtered()
    );
}

