#[test]
fn the_statistics_menu_opens_the_window() {
    let rig = Rig::sample();
    let specs = mychess_gui::windows::menu_bar::menu_specs(
        &rig.shell.app,
        &rig.shell.ui,
        mychess_gui::ViewOptions::default(),
    );
    // Spec M9-7 D4605: the report moved from Tools to Statistics.
    let tools = specs.iter().find(|s| s.label_key == "menu-stats").unwrap();
    let entry = tools
        .entries
        .iter()
        .find_map(|e| match e {
            mychess_gui::windows::menu_bar::MenuEntry::Item {
                label: mychess_gui::windows::menu_bar::Label::Key("menu-tools-opening-report"),
                action,
                shortcut,
                ..
            } => Some((action.clone(), *shortcut)),
            _ => None,
        })
        .expect("the entry");
    assert!(matches!(
        entry.0,
        Some(Message::OpRep(OpRepUiMessage::Open))
    ));
    assert!(entry.1.is_none(), "no default key (D3631)");
}

#[test]
fn quitting_with_the_job_in_flight_cancels_it() {
    let mut rig = Rig::sample();
    let task = rig.once(Message::OpRep(OpRepUiMessage::Open));
    drop(task);
    assert!(rig.shell.app.opening_report().is_running());
    drop(rig.once(Message::Ui(UiMessage::CloseRequested)));
    assert!(!rig.shell.app.opening_report().is_running());
}
