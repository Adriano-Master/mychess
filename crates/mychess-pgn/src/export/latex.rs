//! LaTeX writer for games, for `xskak` and KOMA-Script (decisions D3709 to
//! D3712 of `docs/specs/m7-4-exportacao.md`).
//!
//! The structure follows Scid: a `tabularx` header, `\newchessgame`,
//! `\mainline{...}`, variations in `longfbox` blocks with `\variation{...}`
//! (`\variation[invar]` below the first level), comments as paragraphs,
//! diagrams as `\chessboard`. The evaluation graph (`pgfplots`) is not
//! written (ADR 0011). Text from the game is escaped completely.

use std::io::Write;

use mychess_core::{
    BoardMark, EmbeddedCommand, Game, MarkKind, Position, embedded_commands, strip_mark_codes,
};

use super::escape::{push_fmt, push_latex_escaped};
use super::nag_latex::latex_nag;
use super::walk::{Ev, walk};
use crate::write::WriteError;

const NAG_DIAGRAM: u8 = 201;

/// Options of [`write_game_latex`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LatexOptions {
    /// Write comments (`[%...]` blocks are always removed).
    pub comments: bool,
    /// Write variations.
    pub variations: bool,
    /// Draw the diagrams from Black's side (`inverse`).
    pub flip: bool,
    /// Write a null move as a comment instead of `--` (which `xskak`
    /// cannot parse).
    pub convert_null_moves: bool,
    /// Text written before the first game by [`write_latex_document`].
    pub start: String,
    /// Text written after the last game by [`write_latex_document`].
    pub end: String,
}

impl Default for LatexOptions {
    fn default() -> LatexOptions {
        LatexOptions {
            comments: true,
            variations: true,
            flip: false,
            convert_null_moves: true,
            start: default_latex_start().to_owned(),
            end: default_latex_end().to_owned(),
        }
    }
}

