const PRE_VARIATION_BLOCK: &str = "\n\\begin{longfbox}[margin-left=2em, breakable=true, border-right-style=none, border-top-style=none,]\n";
const POST_VARIATION_BLOCK: &str = "\\end{longfbox}\n";
const RESTART_VARIATION: &str = "\\textcolor{VariationColor}{ \\variation{";
const RESTART_SUB_VARIATION: &str = "\\textcolor{VariationColor}{ \\variation[invar]{";
const STOP_VARIATION: &str = "} }\n\n";

/// Color names that plain `xcolor` knows (lower case).
const XCOLOR_NAMES: [&str; 19] = [
    "black",
    "blue",
    "brown",
    "cyan",
    "darkgray",
    "gray",
    "green",
    "lightgray",
    "lime",
    "magenta",
    "olive",
    "orange",
    "pink",
    "purple",
    "red",
    "teal",
    "violet",
    "white",
    "yellow",
];

/// A color `xcolor` understands: a basic name as it is, `#rrggbb` as an HTML
/// color, anything else red (Tk names such as `firebrick` are not `xcolor`
/// names).
fn latex_color(color: &str) -> String {
    let lower = color.to_ascii_lowercase();
    if XCOLOR_NAMES.contains(&lower.as_str()) {
        return lower;
    }
    if let Some(hex) = color.strip_prefix('#')
        && hex.len() == 6
        && hex.bytes().all(|b| b.is_ascii_hexdigit())
    {
        return format!("{{[HTML]{}}}", hex.to_ascii_uppercase());
    }
    "red".to_owned()
}

/// The `chessboard` keys for the marks of a comment, as Scid's
/// `LaTexDrawMarkCodes`: a newline, then one `,key=value...` line per mark.
fn push_mark_keys(out: &mut String, comment: &str) {
    out.push('\n');
    for cmd in embedded_commands(comment) {
        let EmbeddedCommand::Mark(BoardMark {
            kind,
            from,
            to,
            color,
        }) = cmd
        else {
            continue;
        };
        let color = latex_color(&color);
        match (kind, to) {
            (MarkKind::Arrow, Some(to)) => push_fmt(
                out,
                format_args!(",pgfstyle=straightmove,color={color},markmoves={from}-{to}\n"),
            ),
            (MarkKind::Circle, _) => push_fmt(
                out,
                format_args!(",pgfstyle=circle,padding=-0.1em,color={color},backfields={from}\n"),
            ),
            (MarkKind::Disk, _) => push_fmt(
                out,
                format_args!(
                    ",pgfstyle={{[fill]circle}},padding=-0.1em,color={color},backfields={from}\n"
                ),
            ),
            (MarkKind::Full, _) => push_fmt(
                out,
                format_args!(",pgfstyle=color,color={color},backfields={from}\n"),
            ),
            (MarkKind::Square, _) => push_fmt(
                out,
                format_args!(",pgfstyle=border,color={color},markfields={from}\n"),
            ),
            _ => {}
        }
    }
}

fn has_marks(comment: &str) -> bool {
    embedded_commands(comment)
        .iter()
        .any(|c| matches!(c, EmbeddedCommand::Mark(_)))
}

fn move_id(pos: &Position) -> String {
    format!(
        "moveid={}{},setfen={}",
        pos.fullmove_number(),
        if pos.turn() == mychess_core::Color::White {
            'w'
        } else {
            'b'
        },
        pos.fen()
    )
}

struct Renderer<'a> {
    opts: &'a LatexOptions,
    out: String,
    /// Per level: the `\mainline{` / `\variation{` group is open.
    open: Vec<bool>,
    need_number: Vec<bool>,
    /// Position after the last main-line move (to restore after a diagram in
    /// a variation).
    main_pos: Option<Position>,
}

impl Renderer<'_> {
    fn depth(&self) -> usize {
        self.open.len().saturating_sub(1)
    }

    fn open_line(&mut self) {
        let depth = self.depth();
        if let Some(open) = self.open.last_mut()
            && !*open
        {
            *open = true;
            self.out.push_str(match depth {
                0 => "\\mainline{",
                1 => RESTART_VARIATION,
                _ => RESTART_SUB_VARIATION,
            });
        }
    }

    fn close_line(&mut self) {
        let depth = self.depth();
        if let Some(open) = self.open.last_mut()
            && *open
        {
            *open = false;
            self.out
                .push_str(if depth == 0 { "}\n" } else { STOP_VARIATION });
        }
    }

    fn set_need(&mut self) {
        if let Some(n) = self.need_number.last_mut() {
            *n = true;
        }
    }

    fn comment_paragraph(&mut self, text: &str) {
        let stripped = strip_mark_codes(text);
        let t = stripped.trim();
        if t.is_empty() {
            return;
        }
        self.close_line();
        push_latex_escaped(&mut self.out, t);
        self.out.push_str("\\\\[1ex]\n");
        self.set_need();
    }

    /// `\chessboard` for `pos`; `san` is the move just played on the main
    /// line, whose squares are marked.
    fn chessboard(&mut self, pos: &Position, last_san: Option<&str>, comment: Option<&str>) {
        let in_var = self.depth() > 0;
        self.close_line();
        if in_var {
            self.out.push_str("\\newchessgame[");
            self.out.push_str(&move_id(pos));
            self.out.push_str("]\n");
        }
        self.out
            .push_str("\\begin{center}\n\\vspace{1ex}\n\\chessboard[showmover=true");
        if !in_var && last_san.is_some_and(|s| !s.starts_with("O-O")) {
            self.out.push_str(
                ",lastmoveid,pgfstyle=border,color=gray,markfields={\\xskakget{moveto},\\xskakget{movefrom}},pgfstyle=straightmove,markmove=\\xskakget{movefrom}-\\xskakget{moveto}",
            );
        }
        if let Some(c) = comment {
            push_mark_keys(&mut self.out, c);
        }
        if self.opts.flip {
            self.out.push_str(",inverse");
        }
        if in_var {
            self.out.push_str(",tinyboard");
        }
        self.out.push_str("]\\vspace{1ex}\n\\end{center}\n");
        if in_var && let Some(main) = self.main_pos.clone() {
            self.out.push_str("\\newchessgame[");
            self.out.push_str(&move_id(&main));
            self.out.push_str("]\n");
        }
        self.set_need();
    }
}

fn push_header(out: &mut String, game: &Game) {
    let tags = game.tags();
    let rating = |r: Option<mychess_core::Rating>| {
        r.filter(|r| r.value.get() > 0)
            .map(|r| format!("({})", r.value.get()))
            .unwrap_or_default()
    };
    out.push_str("\\twocolumn[\n\\begin{@twocolumnfalse}\n{\n\\center\n\\begin{tabularx}{0.9\\textwidth}{rllXr}\n\n");
    out.push_str("White: & ");
    push_latex_escaped(out, &tags.white);
    out.push_str(" & ");
    out.push_str(&rating(tags.white_rating));
    out.push_str(" & & ");
    push_latex_escaped(out, &tags.event);
    if !tags.round.is_empty() && tags.round != "?" {
        out.push_str(" (");
        push_latex_escaped(out, &tags.round);
        out.push(')');
    }
    out.push_str("\\\\\nBlack: & ");
    push_latex_escaped(out, &tags.black);
    out.push_str(" & ");
    out.push_str(&rating(tags.black_rating));
    out.push_str(" & & ");
    if !tags.site.is_empty() && tags.site != "?" {
        push_latex_escaped(out, &tags.site);
    }
    out.push_str("\\\\\n");
    match tags.eco {
        Some(eco) => {
            out.push_str("Opening ECO: & ");
            push_latex_escaped(out, &eco.to_string());
            out.push_str(" & & & ");
        }
        None => out.push_str(" & & & & "),
    }
    push_latex_escaped(out, &tags.date.short());
    out.push_str("\\\\\nResult: & ");
    out.push_str(tags.result.as_str());
    out.push_str("\\\\\n\\end{tabularx}\n\\\\[1ex]\n}\n\n");
    out.push_str("\\hrulefill\n\\\\\n\\end{@twocolumnfalse}\n]\n");
}

/// Renders one game as LaTeX text.
pub fn game_to_latex_string(game: &Game, opts: &LatexOptions) -> Result<String, WriteError> {
    let mut r = Renderer {
        opts,
        out: String::new(),
        open: vec![false],
        need_number: vec![true],
        main_pos: None,
    };
    push_header(&mut r.out, game);
    r.out.push_str("\n\\newchessgame\n");
    let start = game.start_position();
    let initial = game.initial_comment();
    let non_standard = start.fen() != Position::new().fen();
    if non_standard {
        r.out.push_str("Fen: ");
        push_latex_escaped(&mut r.out, &start.fen());
        r.out.push_str("\n\\newchessgame[");
        r.out.push_str(&move_id(start));
        r.out.push_str("]\n");
    }
    if non_standard || initial.is_some_and(has_marks) {
        r.chessboard(start, None, initial);
    }
    if opts.comments
        && let Some(text) = initial
    {
        r.comment_paragraph(text);
    }
    r.out.push_str("\\begin{addmargin}[0pt]{0pt}\n");
    {
        let rr = &mut r;
        walk(game, opts.variations, |ev| match ev {
            Ev::Move(m) => {
                if m.depth == 0 {
                    rr.main_pos = Some(m.after.clone());
                }
                if m.first_in_line
                    && m.depth > 0
                    && rr.opts.comments
                    && let Some(text) = m.comment_before
                {
                    rr.comment_paragraph(text);
                }
                if m.is_null && rr.opts.convert_null_moves {
                    rr.comment_paragraph("null move");
                    return;
                }
                rr.open_line();
                let need = rr.need_number.last().copied().unwrap_or(true);
                if m.white || need {
                    rr.out.push_str(&m.number.to_string());
                    rr.out.push_str(if m.white { ". " } else { "... " });
                }
                if let Some(n) = rr.need_number.last_mut() {
                    *n = false;
                }
                push_latex_escaped(&mut rr.out, &m.san);
                let mut diagram = false;
                for nag in m.nags {
                    if nag.value() == NAG_DIAGRAM {
                        diagram = true;
                    } else if let Some(text) = latex_nag(*nag) {
                        rr.out.push_str(text);
                    }
                }
                rr.out.push(' ');
                if diagram {
                    rr.chessboard(m.after, Some(&m.san), m.comment);
                }
                if rr.opts.comments
                    && let Some(text) = m.comment
                {
                    rr.comment_paragraph(text);
                }
            }
            Ev::VarStart => {
                rr.close_line();
                rr.out.push_str(PRE_VARIATION_BLOCK);
                rr.open.push(false);
                rr.need_number.push(true);
            }
            Ev::VarEnd => {
                rr.close_line();
                rr.out.push_str(POST_VARIATION_BLOCK);
                rr.open.pop();
                rr.need_number.pop();
                rr.set_need();
            }
        })?;
    }
    r.close_line();
    r.out.push_str("\\end{addmargin}\n\n\\textbf{");
    r.out.push_str(game.tags().result.as_str());
    r.out.push_str("}\n \\hrule \n\n");
    Ok(r.out)
}

/// Writes one game as LaTeX (no start or end text).
pub fn write_game_latex<W: Write>(
    w: &mut W,
    game: &Game,
    opts: &LatexOptions,
) -> Result<(), WriteError> {
    let text = game_to_latex_string(game, opts)?;
    w.write_all(text.as_bytes())?;
    Ok(())
}

/// Writes a complete document: the start text, every game and the end text.
pub fn write_latex_document<W: Write>(
    w: &mut W,
    games: &[&Game],
    opts: &LatexOptions,
) -> Result<(), WriteError> {
    let mut text = opts.start.clone();
    for game in games {
        text.push_str(&game_to_latex_string(game, opts)?);
    }
    text.push_str(&opts.end);
    w.write_all(text.as_bytes())?;
    Ok(())
}
