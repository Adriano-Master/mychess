/// Replaces `{n}` and `{max}` in a template.
pub(crate) fn fill(template: &str, n: impl std::fmt::Display, max: Option<u32>) -> String {
    let mut out = template.replace("{n}", &n.to_string());
    if let Some(max) = max {
        out = out.replace("{max}", &max.to_string());
    }
    out
}

/// A count with the thousands separator.
pub(crate) fn thousands(n: u32, sep: &str) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            let _ = write!(out, "{sep}");
        }
        out.push(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fills_templates() {
        assert_eq!(
            fill("once every {n} games", 140, None),
            "once every 140 games"
        );
        assert_eq!(fill("{n} of {max}", 3, Some(8)), "3 of 8");
    }

    #[test]
    fn thousands_groups_by_three() {
        assert_eq!(thousands(0, ","), "0");
        assert_eq!(thousands(999, ","), "999");
        assert_eq!(thousands(1000, ","), "1,000");
        assert_eq!(thousands(1_234_567, "."), "1.234.567");
    }
}
